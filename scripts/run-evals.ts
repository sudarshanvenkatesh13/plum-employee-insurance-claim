import { writeFileSync } from "node:fs";
import { runEvals } from "@/src/lib/eval-runner";

function summarizeTrace(response: Awaited<ReturnType<typeof runEvals>>[number]["response"]) {
  return response.trace.map((event) => `- ${event.agent} [${event.status}]: ${event.title} - ${event.detail}`).join("\n");
}

async function main() {
  const results = await runEvals();
  const passed = results.filter((result) => result.passed).length;

  const markdown = `# Eval Report

Generated by \`npm run eval\`.

## Summary

${passed}/${results.length} test cases matched the expected decision outcome.

${results
  .map((result) => {
    const response = result.response;
    const amount = response.status === "DECIDED" ? response.approved_amount : "N/A";
    const reason = response.status === "DECIDED" ? response.reason : response.message;
    return `## ${result.case_id}: ${result.case_name}

- Expected decision: ${result.expected_decision ?? "early stop"}
- Actual decision: ${result.actual_decision ?? "early stop"}
- Passed: ${result.passed ? "yes" : "no"}
- Approved amount: ${amount}
- Confidence: ${Math.round(response.confidence_score * 100)}%
- Reason: ${reason}

### Trace

${summarizeTrace(response)}
`;
  })
  .join("\n")}
`;

  writeFileSync("docs/EVAL_REPORT.md", markdown);
  console.log(`${passed}/${results.length} eval cases passed. Report written to docs/EVAL_REPORT.md`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
